import React, { useState, useEffect, useMemo } from "react";
import ReactDOM from 'react-dom';
import Dropdown from '../../../Components/shared/Dropdown'; 
import '../../../GlobalStyle/GlobalForm.css';
import '../../../GlobalStyle/GlobalOverlay.css';
import '../../../GlobalStyle/Global.css';
import ConfirmationModal from '../ConfirmationModal';

function AddSection({
  onClose,
  onSuccess,
  programId,
  programName,
  programAbbr,
  sectionToEdit = null,
}) {
  const isEditMode = !!sectionToEdit;

  const [sectionOption, setSectionOption] = useState("new");
  const [sectionNumber, setSectionNumber] = useState("");
  const [selectedSectionId, setSelectedSectionId] = useState("");
  const [yearLevel, setYearLevel] = useState("");
  const [semesterId, setSemesterId] = useState("");
  const [academicYearId, setAcademicYearId] = useState("");
  const [adviserId, setAdviserId] = useState("");
  const [isActive, setIsActive] = useState(true);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [academicYears, setAcademicYears] = useState([]);
  const [faculties, setFaculties] = useState([]);
  const [existingSections, setExistingSections] = useState([]);
  const [portalRoot, setPortalRoot] = useState(document.getElementById('portal-root') || document.body);
  const [confirmState, setConfirmState] = useState({ isOpen: false });
  const [successState, setSuccessState] = useState({ isOpen: false });

  const autoGeneratedName = useMemo(() => {
    if (!programAbbr) return "";

    let result = programAbbr;

    if (yearLevel) {
      result += ` ${yearLevel}`;
    }

    if (semesterId) {
      const semNumber = semesterId === '1' ? '1' : semesterId === '2' ? '2' : '3';
      result += `-Y${semNumber}`;
    }

    if (sectionNumber) {
      result += `-${sectionNumber}`;
    }

    return result;
  }, [programAbbr, yearLevel, semesterId, sectionNumber]);

  const closeConfirm = () => setConfirmState({ isOpen: false });

  const openAlert = (title, summary, variant = 'info') => {
    setConfirmState({
      isOpen: true,
      title,
      summary,
      variant,
      isAlert: true,
      onConfirm: closeConfirm,
      onCancel: closeConfirm,
    });
  };

  const showSuccess = (title, summary) => {
    setSuccessState({ isOpen: true, title, summary, variant: 'success' });
  };

  // --- Populate fields when editing ---
  useEffect(() => {
    if (!sectionToEdit) return;

    setSectionOption("existing");
    setSelectedSectionId(sectionToEdit.section_id?.toString() || "");
    setYearLevel(sectionToEdit.year_level?.toString() || "");
    setSemesterId(sectionToEdit.semester_id?.toString() || "");
    setAcademicYearId(
      (sectionToEdit.year_id ?? sectionToEdit.academic_year_id)?.toString() || ""
    );
    setAdviserId(sectionToEdit.adviser_id?.toString() || "");
    setIsActive(sectionToEdit.is_active !== false);

    if (sectionToEdit.section_number != null) {
      setSectionNumber(String(sectionToEdit.section_number));
    }
  }, [sectionToEdit]);

  useEffect(() => {
    const fetchData = async () => {
      const token = sessionStorage.getItem('token') || localStorage.getItem('token');
      const headers = { 'Authorization': `Bearer ${token}` };

      try {
        const yearsRes = await fetch(`${process.env.REACT_APP_API_URL}/admin/academic-years`, { headers });
        const yearsData = await yearsRes.json();
        if (yearsData.success) setAcademicYears(yearsData.data);
      } catch (error) {
        console.error("Error fetching academic years:", error);
      }

      try {
        const facultiesRes = await fetch(`${process.env.REACT_APP_API_URL}/admin/faculties`, { headers });
        const facultiesData = await facultiesRes.json();
        if (facultiesData.success) setFaculties(facultiesData.data);
      } catch (error) {
        console.error("Error fetching faculties:", error);
      }

      try {
        const sectionsRes = await fetch(`${process.env.REACT_APP_API_URL}/admin/sections/all?program_id=${programId}`, { headers });
        const sectionsData = await sectionsRes.json();
        if (sectionsData.success) setExistingSections(sectionsData.data);
      } catch (error) {
        console.error("Error fetching sections:", error);
      }
    };

    fetchData();
  }, [programId]);

  const handleSubmit = async () => {
    if (!isEditMode) {
      if (sectionOption === "new") {
        if (!sectionNumber) {
          openAlert('Missing Fields', 'Please enter section number.', 'warning');
          return;
        }
        if (!yearLevel || !semesterId || !academicYearId) {
          openAlert('Missing Fields', 'Please fill in all required fields.', 'warning');
          return;
        }
      }

      if (sectionOption === "existing" && !selectedSectionId) {
        openAlert('Missing Selection', 'Please select a section.', 'warning');
        return;
      }
    }

    if (!academicYearId) {
      openAlert('Missing Field', 'Please select academic year.', 'warning');
      return;
    }

    setIsSubmitting(true);

    try {
      const token = sessionStorage.getItem('token') || localStorage.getItem('token');

      const url = isEditMode
        ? `${process.env.REACT_APP_API_URL}/admin/section-assignments/${sectionToEdit.assignment_id}`
        : `${process.env.REACT_APP_API_URL}/admin/section-assignments`;

      const method = isEditMode ? 'PUT' : 'POST';

      const response = await fetch(url, {
        method,
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${token}`
        },
        body: JSON.stringify({
          section_option: sectionOption,
          section_name: sectionOption === "new" ? autoGeneratedName : null,
          section_number: sectionOption === "new" ? parseInt(sectionNumber) : null,
          section_id: selectedSectionId || null,
          program_id: programId,
          year_level: yearLevel ? parseInt(yearLevel) : null,
          semester_id: semesterId ? parseInt(semesterId) : null,
          year_id: parseInt(academicYearId),
          adviser_id: adviserId ? parseInt(adviserId) : null,
          is_active: isActive
        })
      });

      const data = await response.json();

      if (data.success) {
        showSuccess(
          isEditMode ? 'Section Updated' : 'Section Assignment Added',
          isEditMode
            ? 'The section assignment has been updated successfully.'
            : 'The section assignment has been added successfully.'
        );
      } else {
        openAlert(
          isEditMode ? 'Update Failed' : 'Creation Failed',
          data.message || 'Failed to save section assignment.',
          'danger'
        );
      }
    } catch (error) {
      console.error("Error saving section assignment:", error);
      openAlert('Connection Error', 'An unexpected error occurred. Please try again.', 'danger');
    } finally {
      setIsSubmitting(false);
    }
  };

  // --- Dropdown Options ---
  const sectionOptionChoices = [
    { value: "new", label: "Create New Section" },
    { value: "existing", label: "Use Existing Section" }
  ];

  const yearLevelChoices = [
    { value: "", label: "Select Year Level" },
    { value: "1", label: "1st Year" },
    { value: "2", label: "2nd Year" },
    { value: "3", label: "3rd Year" },
    { value: "4", label: "4th Year" },
    { value: "5", label: "5th Year" }
  ];

  const semesterChoices = [
    { value: "", label: "Select Semester" },
    { value: "1", label: "1st Semester" },
    { value: "2", label: "2nd Semester" },
    { value: "3", label: "Summer Term" }
  ];

  const existingSectionChoices = [
    { value: "", label: "Select Section" },
    ...existingSections.map(section => ({
      value: section.section_id,
      label: section.section_name
    }))
  ];

  const academicYearChoices = [
    { value: "", label: "Select Academic Year" },
    ...academicYears.map(year => ({
      value: year.year_id,
      label: `${year.year_label} ${year.is_active ? '(Current)' : ''}`
    }))
  ];

  const adviserChoices = [
    { value: "", label: "Select Adviser" },
    ...faculties.map(faculty => ({
      value: faculty.faculty_id,
      label: `${faculty.first_name} ${faculty.last_name} (${faculty.designation_name || 'Faculty'})`
    }))
  ];

  const modalContent = (
    <div className="modalOverlay">
      <div className="modalContainer">

        <div className="modalHeader">
          <h3 className="modalTitle">
            {isEditMode ? "UPDATE SECTION ASSIGNMENT" : "ADD SECTION ASSIGNMENT"}
          </h3>
          <div className="CloseBtnArea">
            <button className="CloseBtn" onClick={onClose} disabled={isSubmitting}>&times;</button>
          </div>
        </div>

        <div className="modalScrollArea">
          <div className="FormContent">

            {/* Section option dropdown — only when creating */}
            {!isEditMode && (
              <div className="formGroup">
                <label className="formLabel">SECTION OPTION <span style={{color: 'red'}}>*</span></label>
                <Dropdown
                  options={sectionOptionChoices}
                  value={sectionOption}
                  onChange={setSectionOption}
                  placeholder="Select Option"
                />
              </div>
            )}

            {/* Edit mode: show the section name as read-only */}
            {isEditMode ? (
              <div className="formGroup">
                <label className="formLabel">SECTION</label>
                <input
                  type="text"
                  value={sectionToEdit.section_name || ""}
                  disabled
                  className="readOnlyInput"
                />
              </div>
            ) : sectionOption === "new" ? (
              <>
                <div className="formRow">
                  <div className="formGroup">
                    <label className="formLabel">YEAR LEVEL <span style={{color: 'red'}}>*</span></label>
                    <Dropdown
                      options={yearLevelChoices}
                      value={yearLevel}
                      onChange={setYearLevel}
                      placeholder="Select Year Level"
                    />
                  </div>

                  <div className="formGroup">
                    <label className="formLabel">SEMESTER <span style={{color: 'red'}}>*</span></label>
                    <Dropdown
                      options={semesterChoices}
                      value={semesterId}
                      onChange={setSemesterId}
                      placeholder="Select Semester"
                    />
                  </div>
                </div>

                <div className="formRow">
                  <div className="formGroup">
                    <label className="formLabel">SECTION NUMBER <span style={{color: 'red'}}>*</span></label>
                    <input
                      type="number"
                      placeholder="1"
                      min="1"
                      value={sectionNumber}
                      onChange={(e) => setSectionNumber(e.target.value)}
                    />
                  </div>
                  <div className="formGroup">
                    <label className="formLabel">SECTION NAME</label>
                    <input
                      type="text"
                      value={autoGeneratedName}
                      disabled
                      className="readOnlyInput"
                      placeholder="Will auto-generate"
                    />
                  </div>
                </div>
              </>
            ) : (
              <div className="formGroup">
                <label className="formLabel">EXISTING SECTION <span style={{color: 'red'}}>*</span></label>
                <Dropdown
                  options={existingSectionChoices}
                  value={selectedSectionId}
                  onChange={setSelectedSectionId}
                  placeholder="Select Section"
                />
              </div>
            )}

            <div className="formGroup">
              <label className="formLabel">ACADEMIC YEAR <span style={{color: 'red'}}>*</span></label>
              <Dropdown
                options={academicYearChoices}
                value={academicYearId}
                onChange={setAcademicYearId}
                placeholder="Select Academic Year"
              />
            </div>

            <div className="formGroup">
              <label className="formLabel">ADVISER (Optional)</label>
              <Dropdown
                options={adviserChoices}
                value={adviserId}
                onChange={setAdviserId}
                placeholder="Select Adviser"
              />
            </div>

            <div className="formGroup">
              <label className="formLabel">STATUS <span style={{color: 'red'}}>*</span></label>
              <div className="statusToggleContainer" onClick={() => setIsActive(!isActive)}>
                <div className={`statusSwitch ${isActive ? 'active' : 'inactive'}`}>
                  <div className="switchHandle"></div>
                </div>
                <span className={`statusLabel ${isActive ? 'text-active' : 'text-inactive'}`}>
                  {isActive ? "ACTIVE" : "INACTIVE"}
                </span>
              </div>
            </div>

            <div className="BtnsContainer">
              <button className="ResetFilterBtn" onClick={onClose} disabled={isSubmitting}>CANCEL</button>
              <button className="ApplyFilterBtn" onClick={handleSubmit} disabled={isSubmitting}>
                {isSubmitting
                  ? (isEditMode ? "UPDATING..." : "ADDING...")
                  : (isEditMode ? "UPDATE ASSIGNMENT" : "ADD ASSIGNMENT")}
              </button>
            </div>
          </div>
        </div>
      </div>

      <ConfirmationModal
        isOpen={successState.isOpen}
        title={successState.title}
        summary={successState.summary}
        variant={successState.variant}
        isAlert={true}
        onConfirm={() => {
          setSuccessState({ isOpen: false });
          onSuccess();
        }}
        onCancel={() => {
          setSuccessState({ isOpen: false });
          onSuccess();
        }}
      />

      <ConfirmationModal
        isOpen={confirmState.isOpen}
        title={confirmState.title}
        summary={confirmState.summary}
        variant={confirmState.variant}
        isAlert={confirmState.isAlert}
        onConfirm={confirmState.onConfirm}
        onCancel={confirmState.onCancel}
      />
    </div>
  );

  return ReactDOM.createPortal(modalContent, portalRoot);
}

export default AddSection;