import React, { useState, useEffect, useMemo } from "react";
import { BiCollection } from 'react-icons/bi';
import Dropdown from '../../../Components/shared/Dropdown'; 
import ConfirmationModal from '../../../Components/shared/ConfirmationModal';
import Modal from '../../../Components/ui/Modal';
import Button from '../../../Components/ui/Button';
import TextField from '../../../Components/ui/Textfield';
import NumberInput from '../../../Components/ui/NumberInput';
import cx from '../../../Components/ui/Cx';

function AddSection({
  onClose,
  onSuccess,
  programId,
  programName,
  programAbbr,
  sectionToEdit = null,
}) {
  const isEditMode = !!sectionToEdit;

  const [sectionOption, setSectionOption] = useState("new");
  const [sectionNumber, setSectionNumber] = useState("");
  const [selectedSectionId, setSelectedSectionId] = useState("");
  const [yearLevel, setYearLevel] = useState("");
  const [semesterId, setSemesterId] = useState("");
  const [academicYearId, setAcademicYearId] = useState("");
  const [adviserId, setAdviserId] = useState("");
  const [isActive, setIsActive] = useState(true);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isDirty, setIsDirty] = useState(false);
  
  const [academicYears, setAcademicYears] = useState([]);
  const [faculties, setFaculties] = useState([]);
  const [existingSections, setExistingSections] = useState([]);
  
  const [confirmState, setConfirmState] = useState({ isOpen: false });
  const [successState, setSuccessState] = useState({ isOpen: false });

  const autoGeneratedName = useMemo(() => {
    if (!programAbbr) return "";
    let result = programAbbr;
    if (yearLevel) result += ` ${yearLevel}`;
    if (semesterId) {
      const semNumber = semesterId === '1' ? '1' : semesterId === '2' ? '2' : '3';
      result += `-Y${semNumber}`;
    }
    if (sectionNumber) result += `-${sectionNumber}`;
    return result;
  }, [programAbbr, yearLevel, semesterId, sectionNumber]);

  const closeConfirm = () => setConfirmState({ isOpen: false });
  const openAlert = (title, message, variant = 'info') => setConfirmState({ isOpen: true, title, message, variant, isAlert: true, onConfirm: closeConfirm, onCancel: closeConfirm });
  const showSuccess = (title, summary) => setSuccessState({ isOpen: true, title, summary, variant: 'success' });

  useEffect(() => {
    if (!sectionToEdit) return;
    setSectionOption("existing");
    setSelectedSectionId(sectionToEdit.section_id?.toString() || "");
    setYearLevel(sectionToEdit.year_level?.toString() || "");
    setSemesterId(sectionToEdit.semester_id?.toString() || "");
    setAcademicYearId((sectionToEdit.year_id ?? sectionToEdit.academic_year_id)?.toString() || "");
    setAdviserId(sectionToEdit.adviser_id?.toString() || "");
    setIsActive(sectionToEdit.is_active !== false);
    if (sectionToEdit.section_number != null) setSectionNumber(String(sectionToEdit.section_number));
  }, [sectionToEdit]);

  useEffect(() => {
    const fetchData = async () => {
      const token = sessionStorage.getItem('token') || localStorage.getItem('token');
      const headers = { 'Authorization': `Bearer ${token}` };

      try {
        const yearsRes = await fetch(`${process.env.REACT_APP_API_URL}/admin/academic-years`, { headers });
        const yearsData = await yearsRes.json();
        if (yearsData.success) setAcademicYears(yearsData.data);
      } catch (error) { console.error("Error fetching years:", error); }

      try {
        const facultiesRes = await fetch(`${process.env.REACT_APP_API_URL}/admin/faculties`, { headers });
        const facultiesData = await facultiesRes.json();
        if (facultiesData.success) setFaculties(facultiesData.data);
      } catch (error) { console.error("Error fetching faculties:", error); }

      try {
        const sectionsRes = await fetch(`${process.env.REACT_APP_API_URL}/admin/sections/all?program_id=${programId}`, { headers });
        const sectionsData = await sectionsRes.json();
        if (sectionsData.success) setExistingSections(sectionsData.data);
      } catch (error) { console.error("Error fetching sections:", error); }
    };

    fetchData();
  }, [programId]);

  const handleSubmit = async () => {
    if (!isEditMode) {
      if (sectionOption === "new") {
        if (!sectionNumber) { openAlert('Missing Fields', 'Please enter section number.', 'warning'); return; }
        if (!yearLevel || !semesterId || !academicYearId) { openAlert('Missing Fields', 'Please fill in all required fields.', 'warning'); return; }
      }
      if (sectionOption === "existing" && !selectedSectionId) { openAlert('Missing Selection', 'Please select a section.', 'warning'); return; }
    }
    if (!academicYearId) { openAlert('Missing Field', 'Please select academic year.', 'warning'); return; }

    setIsSubmitting(true);
    try {
      const token = sessionStorage.getItem('token') || localStorage.getItem('token');
      const url = isEditMode
        ? `${process.env.REACT_APP_API_URL}/admin/section-assignments/${sectionToEdit.assignment_id}`
        : `${process.env.REACT_APP_API_URL}/admin/section-assignments`;
      const method = isEditMode ? 'PUT' : 'POST';
      const response = await fetch(url, {
        method,
        headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${token}` },
        body: JSON.stringify({
          section_option: sectionOption,
          section_name: sectionOption === "new" ? autoGeneratedName : null,
          section_number: sectionOption === "new" ? parseInt(sectionNumber) : null,
          section_id: selectedSectionId || null,
          program_id: programId,
          year_level: yearLevel ? parseInt(yearLevel) : null,
          semester_id: semesterId ? parseInt(semesterId) : null,
          year_id: parseInt(academicYearId),
          adviser_id: adviserId ? parseInt(adviserId) : null,
          is_active: isActive
        })
      });
      const data = await response.json();
      if (data.success) {
        setIsDirty(false);
        showSuccess(isEditMode ? 'Section Updated' : 'Section Assignment Added', isEditMode ? 'The section assignment has been updated successfully.' : 'The section assignment has been added successfully.');
      } else {
        openAlert('Save Failed', data.message || 'Failed to save section assignment.', 'danger');
      }
    } catch (error) {
      console.error("Error saving section assignment:", error);
      openAlert('Connection Error', 'An unexpected error occurred. Please try again.', 'danger');
    } finally {
      setIsSubmitting(false);
    }
  };

  const sectionOptionChoices = [
    { value: "new", label: "Create New Section" },
    { value: "existing", label: "Use Existing Section" }
  ];

  const yearLevelChoices = [
    { value: "", label: "Select Year Level" },
    { value: "1", label: "1st Year" },
    { value: "2", label: "2nd Year" },
    { value: "3", label: "3rd Year" },
    { value: "4", label: "4th Year" },
    { value: "5", label: "5th Year" }
  ];

  const semesterChoices = [
    { value: "", label: "Select Semester" },
    { value: "1", label: "1st Semester" },
    { value: "2", label: "2nd Semester" },
    { value: "3", label: "Summer Term" }
  ];

  const existingSectionChoices = [
    { value: "", label: "Select Section" },
    ...existingSections.map(section => ({ value: section.section_id, label: section.section_name }))
  ];

  const academicYearChoices = [
    { value: "", label: "Select Academic Year" },
    ...academicYears.map(year => ({ value: year.year_id, label: `${year.year_label} ${year.is_active ? '(Current)' : ''}` }))
  ];

  const adviserChoices = [
    { value: "", label: "Select Adviser" },
    ...faculties.map(faculty => ({ value: faculty.faculty_id, label: `${faculty.first_name} ${faculty.last_name} (${faculty.designation_name || 'Faculty'})` }))
  ];

  return (
    <>
      <Modal
        isOpen={true}
        onClose={onClose}
        title={isEditMode ? "Update Section Assignment" : "Add Section Assignment"}
        description={`Assign a section for ${programName}.`}
        icon={<BiCollection className="text-2xl" />}
        loading={isSubmitting}
        isDirty={isDirty}
        footer={({ requestClose }) => (
          <>
            <Button type="button" variant="secondary" onClick={requestClose} disabled={isSubmitting}>
              Cancel
            </Button>
            <Button type="button" variant="primary" onClick={handleSubmit} loading={isSubmitting} disabled={!isDirty}>
              {isSubmitting ? "Saving..." : (isEditMode ? "Update Assignment" : "Add Assignment")}
            </Button>
          </>
        )}
      >
        <div className="space-y-6">
          {/* Section Option (only when creating) */}
          {!isEditMode && (
            <div className="space-y-1.5">
              <label className="block text-sm font-medium text-ink">Section Option <span className="text-danger">*</span></label>
              <Dropdown
                options={sectionOptionChoices}
                value={sectionOption}
                onChange={(val) => { setIsDirty(true); setSectionOption(val); }}
                placeholder="Select Option"
              />
            </div>
          )}

          {isEditMode && (
            <TextField label="Section" value={sectionToEdit.section_name || ""} disabled className="opacity-60" />
          )}

          {!isEditMode && sectionOption === "new" && (
            <div className="space-y-4">
              <div className="grid gap-4 sm:grid-cols-2">
                <div className="space-y-1.5">
                  <label className="block text-sm font-medium text-ink">Year Level <span className="text-danger">*</span></label>
                  <Dropdown options={yearLevelChoices} value={yearLevel} onChange={(val) => { setIsDirty(true); setYearLevel(val); }} placeholder="Select Year Level" />
                </div>
                <div className="space-y-1.5">
                  <label className="block text-sm font-medium text-ink">Semester <span className="text-danger">*</span></label>
                  <Dropdown options={semesterChoices} value={semesterId} onChange={(val) => { setIsDirty(true); setSemesterId(val); }} placeholder="Select Semester" />
                </div>
              </div>

              <div className="grid gap-4 sm:grid-cols-2">
                <NumberInput
                  label={<>Section Number <span className="text-danger">*</span></>}
                  placeholder="1"
                  min="1"
                  value={sectionNumber}
                  onChange={(e) => { setIsDirty(true); setSectionNumber(e.target.value); }}
                />
                <TextField label="Section Name (auto-generated)" value={autoGeneratedName} disabled placeholder="Will auto-generate" className="opacity-60" />
              </div>
            </div>
          )}

          {!isEditMode && sectionOption === "existing" && (
            <div className="space-y-1.5">
              <label className="block text-sm font-medium text-ink">Existing Section <span className="text-danger">*</span></label>
              <Dropdown options={existingSectionChoices} value={selectedSectionId} onChange={(val) => { setIsDirty(true); setSelectedSectionId(val); }} placeholder="Select Section" />
            </div>
          )}

          <div className="space-y-1.5">
            <label className="block text-sm font-medium text-ink">Academic Year <span className="text-danger">*</span></label>
            <Dropdown options={academicYearChoices} value={academicYearId} onChange={(val) => { setIsDirty(true); setAcademicYearId(val); }} placeholder="Select Academic Year" />
          </div>

          <div className="space-y-1.5">
            <label className="block text-sm font-medium text-ink">Adviser <span className="text-ink-3">(Optional)</span></label>
            <Dropdown options={adviserChoices} value={adviserId} onChange={(val) => { setIsDirty(true); setAdviserId(val); }} placeholder="Select Adviser" />
          </div>

          <div className="space-y-3 pt-2">
            <label className="block text-sm font-medium text-ink">Status <span className="text-danger">*</span></label>
            <div className="flex cursor-pointer items-center gap-3" onClick={() => { setIsDirty(true); setIsActive(!isActive); }}>
              <div className={cx("relative h-6 w-11 rounded-full transition-colors duration-200 ease-in-out", isActive ? "bg-brand" : "bg-line-strong")}>
                <div className={cx("absolute top-1 h-4 w-4 rounded-full bg-white shadow-sm transition-transform duration-200 ease-in-out", isActive ? "translate-x-6" : "translate-x-1")} />
              </div>
              <span className={cx("text-sm font-medium transition-colors", isActive ? "text-brand-ink" : "text-ink-2")}>{isActive ? "Active" : "Inactive"}</span>
            </div>
          </div>
        </div>
      </Modal>

      <ConfirmationModal isOpen={successState.isOpen} title={successState.title} summary={successState.summary} variant={successState.variant} isAlert={true} onConfirm={() => { setSuccessState({ isOpen: false }); onSuccess(); }} onCancel={() => { setSuccessState({ isOpen: false }); onSuccess(); }} />
      <ConfirmationModal isOpen={confirmState.isOpen} title={confirmState.title} message={confirmState.message} variant={confirmState.variant} isAlert={confirmState.isAlert} onConfirm={confirmState.onConfirm} onCancel={confirmState.onCancel} />
    </>
  );
}

export default AddSection;